// Package ignore translates gitignore-syntax rules into rclone filter rules.
//
// docs/peps/0001 "Command line": ignore rules are written in gitignore syntax
// and translated to rclone filters (https://rclone.org/filtering/). rclone, not
// folder-sync, then applies them, so there is one matcher, not two.
//
// The two syntaxes differ in three ways this translation handles:
//   - gitignore's last matching rule wins; rclone's first match wins, so the
//     rule order is reversed.
//   - A gitignore pattern without a slash matches at any depth; with a slash
//     (other than a trailing one) it is anchored to the folder root. rclone
//     anchors only on a leading "/", so a middle slash gains a leading one.
//   - A gitignore pattern matches a directory and everything under it; rclone
//     matches files, so every pattern also gets a "/**" twin.
//
// Known gap: gitignore cannot re-include a file whose parent directory is
// excluded; rclone can. A "!" rule therefore re-includes a little more than git would.
package ignore

import (
	"bufio"
	"fmt"
	"strings"
)

// Defaults are added to every project (docs/peps/0001 "init").
var Defaults = []string{
	".git/",
	"node_modules/",
	".env",
	"*.pem",
	"id_*",
	"*.key",
}

// Rule is one parsed gitignore line.
type Rule struct {
	Pattern  string // without "!", leading "/" and trailing "/"
	Negate   bool   // "!" re-includes
	Anchored bool   // matched from the folder root
	DirOnly  bool   // trailing "/": only a directory (and so its contents)
	Source   string // the original line
}

// Parse reads gitignore lines. Blank lines and "#" comments are skipped;
// "\#" and "\!" escape a leading "#" or "!".
func Parse(lines []string) ([]Rule, error) {
	var rules []Rule
	for _, raw := range lines {
		line := strings.TrimRight(raw, "\r")
		line = trimTrailingSpaces(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		rule := Rule{Source: raw}
		if strings.HasPrefix(line, "!") {
			rule.Negate = true
			line = line[1:]
		} else if strings.HasPrefix(line, `\!`) || strings.HasPrefix(line, `\#`) {
			line = line[1:]
		}
		if strings.HasSuffix(line, "/") {
			rule.DirOnly = true
			line = strings.TrimRight(line, "/")
		}
		if strings.HasPrefix(line, "/") {
			rule.Anchored = true
			line = strings.TrimLeft(line, "/")
		} else if strings.Contains(line, "/") && !strings.HasPrefix(line, "**/") {
			rule.Anchored = true
		}
		if line == "" {
			return nil, fmt.Errorf("ignore rule %q matches nothing", raw)
		}
		rule.Pattern = line
		rules = append(rules, rule)
	}
	return rules, nil
}

// trimTrailingSpaces drops trailing spaces unless escaped with a backslash (gitignore rule).
func trimTrailingSpaces(line string) string {
	for strings.HasSuffix(line, " ") && !strings.HasSuffix(line, `\ `) {
		line = line[:len(line)-1]
	}
	return line
}

// escapeForRclone escapes characters rclone's glob treats specially but gitignore does not.
func escapeForRclone(pattern string) string {
	replacer := strings.NewReplacer("{", `\{`, "}", `\}`)
	return replacer.Replace(pattern)
}

// ToRclone renders rules as rclone filter lines (for --filter-from), first match wins.
func ToRclone(rules []Rule) []string {
	var out []string
	for i := len(rules) - 1; i >= 0; i-- {
		rule := rules[i]
		sign := "- "
		if rule.Negate {
			sign = "+ "
		}
		pattern := escapeForRclone(rule.Pattern)
		if strings.HasPrefix(pattern, "**/") {
			pattern = strings.TrimPrefix(pattern, "**/")
		}
		if rule.Anchored {
			pattern = "/" + pattern
		}
		out = append(out, "# "+strings.TrimSpace(rule.Source))
		if !rule.DirOnly {
			out = append(out, sign+pattern)
		}
		out = append(out, sign+pattern+"/**")
	}
	return out
}

// Compile parses gitignore lines (defaults first, then the project's own, then
// extra) and returns the rclone filter file body.
func Compile(project []string, extra ...string) (string, error) {
	lines := append(append(append([]string{}, Defaults...), project...), extra...)
	rules, err := Parse(lines)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("# Generated by folder-sync from gitignore rules; first match wins.\n")
	for _, line := range ToRclone(rules) {
		b.WriteString(line)
		b.WriteString("\n")
	}
	return b.String(), nil
}

// ReadLines splits text into lines (for an ignore file).
func ReadLines(text string) []string {
	var lines []string
	scanner := bufio.NewScanner(strings.NewReader(text))
	for scanner.Scan() {
		lines = append(lines, scanner.Text())
	}
	return lines
}
