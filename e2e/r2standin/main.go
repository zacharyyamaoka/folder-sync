// Command r2standin is a local stand-in for Cloudflare R2's temporary credentials: a gate in front of an
// S3 store (`rclone serve s3` started with no keys) that refuses every request R2 would refuse for a
// prefix-scoped temporary credential, so an end-to-end test can prove that one person's credentials
// never read or write another person's prefix without a real cloud.
//
//	r2standin serve --listen 127.0.0.1:4910 --backend 127.0.0.1:4911 --account ACCOUNT --parent ID:SECRET [--parent …] [--log FILE]
//	r2standin mint  --account ACCOUNT --parent ID:SECRET --endpoint http://127.0.0.1:4910 --bucket B
//	                [--prefix users/x/] [--scope object-read-write | --actions GetObject,HeadObject] [--ttl 15m]
//
// `mint` prints the credential in folder-sync's credential-process shape (AWS's credential_process plus
// Endpoint, Bucket and Prefix), so a test can name `r2standin mint …` as FOLDER_SYNC_CREDENTIAL_PROCESS.
// Test keys only: the parent pairs are generated by the test that starts the gate.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"net/http"
	"net/url"
	"os"
	"os/signal"
	"strings"
	"syscall"
	"time"
)

type parents map[string]string

func (p parents) String() string { return fmt.Sprintf("%d parent key(s)", len(p)) }

func (p parents) Set(value string) error {
	id, secret, ok := strings.Cut(value, ":")
	if !ok || id == "" || secret == "" {
		return fmt.Errorf("--parent takes ID:SECRET")
	}
	p[id] = secret
	return nil
}

func main() {
	if len(os.Args) < 2 {
		fmt.Fprintln(os.Stderr, "usage: r2standin serve|mint …")
		os.Exit(2)
	}
	switch os.Args[1] {
	case "serve":
		os.Exit(serve(os.Args[2:]))
	case "mint":
		os.Exit(mint(os.Args[2:]))
	default:
		fmt.Fprintf(os.Stderr, "r2standin: unknown command %q\n", os.Args[1])
		os.Exit(2)
	}
}

func serve(args []string) int {
	fs := flag.NewFlagSet("serve", flag.ExitOnError)
	listen := fs.String("listen", "127.0.0.1:4910", "address to answer on")
	backend := fs.String("backend", "127.0.0.1:4911", "the S3 store behind the gate (rclone serve s3, no keys)")
	account := fs.String("account", "", "the account id temporary credentials must name (sub)")
	logPath := fs.String("log", "", "append one JSON line per request here")
	keys := parents{}
	fs.Var(keys, "parent", "a parent key ID:SECRET (repeatable)")
	fs.Parse(args)
	if *account == "" || len(keys) == 0 {
		fmt.Fprintln(os.Stderr, "r2standin serve: --account and at least one --parent are required")
		return 2
	}
	logFile, err := openLog(*logPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, "r2standin serve:", err)
		return 1
	}
	gate := &Gate{Account: *account, Parents: keys, Backend: *backend, Log: logFile}
	server := &http.Server{Addr: *listen, Handler: gate, ReadHeaderTimeout: 10 * time.Second}
	stop := make(chan os.Signal, 1)
	signal.Notify(stop, syscall.SIGTERM, os.Interrupt)
	go func() {
		<-stop
		server.Close()
	}()
	fmt.Fprintf(os.Stderr, "r2standin: gate on %s in front of %s (account %s, %s)\n", *listen, *backend, *account, keys)
	if err := server.ListenAndServe(); err != nil && err != http.ErrServerClosed {
		fmt.Fprintln(os.Stderr, "r2standin serve:", err)
		return 1
	}
	return 0
}

func mint(args []string) int {
	fs := flag.NewFlagSet("mint", flag.ExitOnError)
	account := fs.String("account", "", "the account id (sub)")
	endpoint := fs.String("endpoint", "", "the gate's URL; its host is the aud")
	bucket := fs.String("bucket", "", "the one bucket")
	prefix := fs.String("prefix", "", "the one prefix path (empty: the whole bucket)")
	scope := fs.String("scope", "object-read-write", "the scope (ignored with --actions)")
	actions := fs.String("actions", "", "comma-separated actions instead of a scope")
	ttl := fs.Duration("ttl", 15*time.Minute, "lifetime")
	keys := parents{}
	fs.Var(keys, "parent", "the parent key ID:SECRET")
	fs.Parse(args)
	if *account == "" || *endpoint == "" || *bucket == "" || len(keys) != 1 {
		fmt.Fprintln(os.Stderr, "r2standin mint: --account, --endpoint, --bucket and one --parent are required")
		return 2
	}
	host, err := url.Parse(*endpoint)
	if err != nil || host.Host == "" {
		fmt.Fprintln(os.Stderr, "r2standin mint: --endpoint is not a URL")
		return 2
	}
	claims := map[string]any{}
	if *actions != "" {
		claims["actions"] = strings.Split(*actions, ",")
	} else {
		claims["scope"] = *scope
	}
	if *prefix != "" {
		claims["paths"] = map[string]any{"prefixPaths": []string{*prefix}, "objectPaths": []string{}}
	}
	var id, secret string
	for k, v := range keys {
		id, secret = k, v
	}
	keyID, tempSecret, token, expires := Mint(*account, id, secret, host.Host, *bucket, claims, *ttl, time.Now())
	out := map[string]any{"Version": 1, "AccessKeyId": keyID, "SecretAccessKey": tempSecret, "SessionToken": token,
		"Expiration": expires.Format(time.RFC3339), "Endpoint": *endpoint, "Bucket": *bucket, "Prefix": *prefix,
		"Region": "auto", "Provider": "Cloudflare"}
	json.NewEncoder(os.Stdout).Encode(out)
	return 0
}
